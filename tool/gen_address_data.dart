// Generates packages/nepal_kit/lib/src/address/address_data.dart from the
// sagautam5/local-states-nepal dataset (MIT) copied into
// tool/data/local-states-nepal/.
//
//   dart run tool/gen_address_data.dart
import 'dart:convert';
import 'dart:io';

final _root = File.fromUri(Platform.script).parent.parent.path;

List<Map<String, dynamic>> _read(String name) =>
    (jsonDecode(
              File(
                '$_root/tool/data/local-states-nepal/$name.json',
              ).readAsStringSync(),
            )
            as List)
        .cast<Map<String, dynamic>>();

/// Fixes vowel signs typed as two parts: ा + े for ो, ा + ै for ौ.
String _fix(String s) => s.replaceAll('ाे', 'ो').replaceAll('ाै', 'ौ').trim();

String _q(String s) =>
    "'${_fix(s).replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

void main() {
  final pEn = _read('provinces-en'), pNe = _read('provinces-np');
  final dEn = _read('districts-en'), dNe = _read('districts-np');
  final mEn = _read('municipalities-en'), mNe = _read('municipalities-np');
  for (final (a, b) in [(pEn, pNe), (dEn, dNe), (mEn, mNe)]) {
    if (a.length != b.length) throw StateError('en/np lengths differ');
    for (var i = 0; i < a.length; i++) {
      if (a[i]['id'] != b[i]['id']) throw StateError('ids differ at $i');
    }
  }
  const types = {
    1: 'metropolitan',
    2: 'subMetropolitan',
    3: 'municipality',
    4: 'rural',
  };
  final b = StringBuffer()
    ..writeln(
      '// Generated by tool/gen_address_data.dart from sagautam5/local-states-nepal',
    )
    ..writeln(
      '// (MIT, see tool/data/local-states-nepal/LICENSE). Do not edit by hand.',
    )
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'address.dart';")
    ..writeln()
    ..writeln('const List<Province> provinceData = [');
  for (var i = 0; i < pEn.length; i++) {
    b.writeln(
      '  Province(${pEn[i]['id']}, ${_q(pEn[i]['name'])}, ${_q(pNe[i]['name'])}, '
      '${_q(pEn[i]['headquarter'])}),',
    );
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('const List<District> districtData = [');
  for (var i = 0; i < dEn.length; i++) {
    b.writeln(
      '  District(${dEn[i]['id']}, ${dEn[i]['province_id']}, ${_q(dEn[i]['name'])}, '
      '${_q(dNe[i]['name'])}, ${_q(dEn[i]['headquarter'] ?? '')}),',
    );
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('const List<LocalLevel> localLevelData = [');
  for (var i = 0; i < mEn.length; i++) {
    final m = mEn[i];
    b.writeln(
      '  LocalLevel(${m['id']}, ${m['district_id']}, ${_q(m['name'])}, '
      '${_q(mNe[i]['name'])}, LocalLevelType.${types[m['category_id']]}, '
      '${int.parse('${m['wards']}')}),',
    );
  }
  b.writeln('];');
  final out = File(
    '$_root/packages/nepal_kit/lib/src/address/address_data.dart',
  );
  out.writeAsStringSync(b.toString());
  stdout.writeln(
    'wrote ${out.path}: ${pEn.length} provinces, ${dEn.length} districts, '
    '${mEn.length} local levels',
  );
}
